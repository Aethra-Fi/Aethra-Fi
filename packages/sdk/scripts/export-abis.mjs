// Jalankan di: ROOT/packages/sdk  ->  node scripts/export-abis.mjs
// Copies ABIs from the Foundry build output into typed `as const` modules.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const dest = join(here, "../src/abis");
mkdirSync(dest, { recursive: true });

// [exportName, artifact file, contract name]
const contracts = [
  ["aethraHubAbi", "AethraHub.sol", "AethraHub"],
  ["aethraHookAbi", "AethraHook.sol", "AethraHook"],
  ["aethraRouterAbi", "AethraRouter.sol", "AethraRouter"],
  ["aethraPositionsAbi", "AethraPositions.sol", "AethraPositions"],
  ["dlmmPoolAbi", "DLMMPool.sol", "DLMMPool"],
  ["dlmmFactoryAbi", "DLMMFactory.sol", "DLMMFactory"],
  ["dlmmLimitOrdersAbi", "DLMMLimitOrders.sol", "DLMMLimitOrders"],
  ["dammPoolAbi", "DAMMPool.sol", "DAMMPool"],
  ["dammFactoryAbi", "DAMMFactory.sol", "DAMMFactory"],
  ["launchpadAbi", "AethraLaunchpad.sol", "AethraLaunchpad"],
  ["launchTokenAbi", "LaunchToken.sol", "LaunchToken"],
  ["aethTokenAbi", "AethraToken.sol", "AethraToken"],
  ["lendingVaultAbi", "LendingVault.sol", "LendingVault"],
  ["creditManagerAbi", "CreditManager.sol", "CreditManager"],
  ["buybackAbi", "AethraBuyback.sol", "AethraBuyback"],
  ["faucetTokenAbi", "FaucetToken.sol", "FaucetToken"],
  ["mockPriceFeedAbi", "MockPriceFeed.sol", "MockPriceFeed"],
  ["poolManagerAbi", "IPoolManager.sol", "IPoolManager"],
];

const exported = [];
for (const [name, file, contract] of contracts) {
  const p = join(out, file, `${contract}.json`);
  if (!existsSync(p)) {
    console.warn(`skip ${contract} (not built)`);
    continue;
  }
  const { abi } = JSON.parse(readFileSync(p, "utf8"));
  writeFileSync(join(dest, `${name}.ts`), `// Generated by scripts/export-abis.mjs. Do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`);
  exported.push(name);
}
writeFileSync(
  join(dest, "index.ts"),
  `// Generated by scripts/export-abis.mjs. Do not edit.\n${exported.map((n) => `export { ${n} } from "./${n}.js";`).join("\n")}\n`,
);
console.log(`exported ${exported.length} ABIs`);
